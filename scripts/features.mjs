#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  docPath,
  docRelative,
  findLaunchpad,
  TOOL_ROOT,
} from "./lib/config.mjs";
import { isMainModule } from "./lib/paths.mjs";
import { readFeatureInventory, notElectable } from "./lib/features.mjs";
import { readControl } from "./lib/control-store.mjs";
import { formatDuration } from "./lib/duration.mjs";

const cell = (value) =>
  String(typeof value === "string" ? value : JSON.stringify(value))
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("|", "&#124;")
    .replaceAll("`", "&#96;")
    .replace(/\r?\n/gu, "<br>");

const display = (id, value) => {
  if (value === null) return "null";
  if (id === "retention")
    return Object.entries(value)
      .map(
        ([key, hours]) =>
          `${key}: ${hours === null ? "keep" : formatDuration(hours * 3600000)}`,
      )
      .join("; ");
  if (id === "driven-phase-timeout") return formatDuration(value);
  if (id === "dispatch-bounds")
    return Object.entries(value)
      .map(([role, limits]) => {
        const describe = (limits) =>
          Object.entries(limits)
            .map(([key, bound]) =>
              key === "repair"
                ? `repair (${describe(bound)})`
                : `${key}: ${key === "wallClockMs" && typeof bound === "number" ? formatDuration(bound) : bound}`,
            )
            .join(", ");
        return `${role}: ${describe(limits)}`;
      })
      .join("; ");
  return value;
};

export function renderFeatures(root) {
  const rows = readFeatureInventory(root);
  const contractPath = join(root, "CLAUDE.md");
  const contract = existsSync(contractPath)
    ? readFileSync(contractPath, "utf8")
    : "";
  const count = contract.match(/DotLn has (\d+) refusals/u)?.[1];
  return `# Feature elections\n\nGenerated by \`npm run features -- render\`; edit \`dotln.config.json\` or the named budget key, then run \`npm run meta\`.\n\nScope describes ownership: core rows describe core's release surfaces; instance rows are local choices; both apply in either setting. Unread switches have no effect. A queued order is a future consumer. The driven session ceiling defaults to four times the subagent cap.\n\n| Feature | Scope | Default | Effective value | Source | What it does | Election key | Read by | Note |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n${rows.map((entry) => `| ${[entry.id, entry.scope, display(entry.id, entry.default), display(entry.id, entry.value), entry.source, entry.what, entry.readFrom, entry.readBy, entry.note ?? ""].map(cell).join(" | ")} |`).join("\n")}\n\nNot electable:\n\n${notElectable.map((text, index) => `- ${text}${index === 0 && count ? ` (${count} in the installed contract)` : ""}.`).join("\n")}\n\nThese are the floor; this file cannot turn them off. Desktop-control elects tool access under that floor and still needs the operator's explicit session request.\n`;
}

export function featureAdvisories(root) {
  const messages = [];
  for (const entry of readFeatureInventory(root)) {
    if (
      !/^(core|instance|both)$/u.test(entry.scope) ||
      !entry.what ||
      !entry.readFrom
    )
      throw new Error(`invalid feature registry row: ${entry.id}`);
    if (entry.readBy === "unread") continue;
    if (/^WO-\d{3}$/u.test(entry.readBy)) {
      // A future consumer is a registry declaration, not a dependency on the
      // core order archive in every copied or installed runtime.
      if (readControl(root).orders.get(entry.readBy)?.state.phase === "closed")
        messages.push(
          `feature ${entry.id}: ${entry.readBy} has closed; the next planning pass should identify and register its consumer`,
        );
    } else {
      const emitted = entry.readBy
        .replace(/^packages\/([^/]+)\/src\//u, "packages/$1/dist/src/")
        .replace(/\.ts$/u, ".js");
      if (
        !existsSync(join(TOOL_ROOT, entry.readBy)) &&
        !existsSync(join(TOOL_ROOT, emitted))
      )
        throw new Error(`feature ${entry.id}: missing reader ${entry.readBy}`);
    }
  }
  return messages;
}

export function writeFeatures(root, { check = false } = {}) {
  const text = renderFeatures(root);
  const path = docPath(root, "control", "FEATURES.md");
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text)
      throw new Error(
        `stale ${docRelative(root, "control", "FEATURES.md")}; run npm run features -- render`,
      );
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  return path;
}

export function featuresMain(
  args = process.argv.slice(2),
  root = findLaunchpad(),
) {
  const [command, ...flags] = args;
  if (
    !["list", "render", "check", "--check"].includes(command) ||
    (flags.length &&
      !(command === "list" && flags.length === 1 && flags[0] === "--json"))
  )
    throw new Error("usage: npm run features -- list [--json]|render|check");
  if (command === "list")
    console.log(
      flags.length
        ? JSON.stringify(readFeatureInventory(root), null, 2)
        : renderFeatures(root),
    );
  else {
    for (const message of featureAdvisories(root))
      console.warn(`Advisory: ${message}`);
    writeFeatures(root, { check: command !== "render" });
    console.log(`Features ${command === "render" ? "rendered" : "current"}.`);
  }
}

if (isMainModule(import.meta.url)) {
  try {
    featuresMain();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
