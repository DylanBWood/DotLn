// Reproduce the Release record-link exemption using synthetic local forges.
// Run from the repository root under scripts/harness.mjs bounded.
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { pathToFileURL } from "node:url";
import { resolve, join } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(process.argv[2] ?? process.cwd());
const file = join(root, "scripts/test-target-worktree-release.mjs");
let source = readFileSync(file, "utf8").replace(
  /from "(\.[^"]+)"/g,
  (_, specifier) =>
    `from ${JSON.stringify(new URL(specifier, pathToFileURL(file)).href)}`,
);
source += `
test("final reviewer author-written target URL is not a moved record", () =>
  withFixture((f) => {
    const r = releaseFixture(f, {
      header: "**Target release notes:** reviewed\\n",
      notes: notesText("The product gains a board."),
    });
    const notesPath = "records/final-reviews/WO-999/RELEASE-NOTES.md";
    const note = (revision) => notesText(
      "See [the implementation](https://github.com/dotln-fixture/target/blob/" + revision + "/docs/WO-006-notes.md).",
    );
    r.amendMain(notesPath, note("a".repeat(40)), "docs: author a target link");
    const control = r.close("--publish");
    assert.notEqual(control.status, 0, "the other-revision control must refuse");
    assert.match(control.stderr, /identifier\\.launchpad: WO-006/u);
    assert.equal(r.tags(), "", "the control refuses before any tag push");
    r.amendMain(notesPath, note(r.merged), "docs: point the link at the target commit");
    const candidate = r.close("--publish");
    const publishedBody = r.releases()["v0.1.0"]?.body ?? null;
    console.log("FINAL_REVIEW " + JSON.stringify({
      probe: "author-written-target-url-exemption",
      controlStatus: control.status,
      controlError: control.stderr.trim(),
      candidateStatus: candidate.status,
      candidateError: candidate.stderr.trim(),
      publishedIdentifier: publishedBody?.includes("/docs/WO-006-notes.md") ?? false,
      tagPublished: r.tags() !== "",
      releaseCreated: publishedBody !== null,
      namedPathExists: git(r.remote, "ls-tree", "-r", "--name-only", "main", "--", "docs/WO-006-notes.md") !== "",
    }));
    assert.notEqual(candidate.status, 0, "an author-written URL is not a record link generated by the kit and must retain identifier.launchpad");
    assert.match(candidate.stderr, /identifier\\.launchpad: WO-006/u);
    assert.equal(r.tags(), "", "identifier refusal precedes tag push");
  }));
`;

const scratch = mkdtempSync(join(tmpdir(), "wo227-final-release-"));
try {
  const probe = join(scratch, "release-link.test.mjs");
  writeFileSync(probe, source);
  const run = spawnSync(
    process.execPath,
    [
      "--test",
      "--test-concurrency=1",
      "--test-name-pattern=final reviewer author-written target URL",
      probe,
    ],
    { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
  );
  const redact = (value) =>
    value.replaceAll(scratch, "<tmp>").replaceAll(root, "<worktree>");
  console.log(
    JSON.stringify(
      {
        status: run.status,
        signal: run.signal,
        stdout: redact(run.stdout ?? ""),
        stderr: redact(run.stderr ?? ""),
      },
      null,
      2,
    ),
  );
  process.exitCode = run.status ?? 1;
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
