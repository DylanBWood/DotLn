#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  SEED,
  BASE,
  FACTORS,
  REASONS,
  totalCells,
  sweepAuthority,
  defaultDimensions,
  inputFor,
  runCell,
  event,
} from "./wo103-authority-lib.mjs";
import {
  OUTBOX_FACTORS,
  PERMUTATION_POLICY,
  sweepOutbox,
  outboxCount,
} from "./wo103-outbox-lib.mjs";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const MANIFEST_PATH = "corpus/manifests/WO-103.json";
export const BUDGET = {
  maximumFiles: 16,
  maximumRows: 2048,
  maximumTotalBytes: 12582912,
  rowsPerShard: 128,
};
export const TOOLCHAIN = {
  node: "v26.9.0",
  npm: "11.19.1",
  typescript: "7.0.2",
  platform: "darwin",
  architecture: "arm64",
};
const json = (v) => JSON.stringify(v, null, 2) + "\n";
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
export function auditCarryIns(kernel, audit, seed = SEED) {
  return ["missing-state", "missing-env"].map((environment, i) => {
    const input = inputFor(
      {
        ...defaultDimensions(),
        conditions: 1,
        events: 1,
        semanticMatch: "never",
        environment,
      },
      seed,
    );
    const run = runCell(kernel, input);
    const refusal = { ...run.observed.refusal, eventId: `refusal-${i}` };
    const decision = {
      ...event(`trace-${i}`, "DecisionRecorded", { trace: run.observed.trace }),
      occurredAt: refusal.occurredAt,
    };
    const records = audit.deriveAuditRecords([refusal, decision]);
    return {
      number: `WO-103-F00${i + 1}`,
      cellId: `audit-${environment}`,
      input,
      expected: run.expected.result,
      events: [refusal, decision],
      auditRecords: records,
      traceLinked: records.some((r) => r.eventIds.includes(decision.eventId)),
    };
  });
}
export function buildPrecedenceTable(winners) {
  return `# WO-103 generated precedence table\n\nGenerated by generate-authority-corpus.mjs; regenerate, never edit.\n\n| Rank | Exact shipped reason | Winning cells |\n| --- | --- | --- |\n${REASONS.map((reason, i) => `| ${i + 1} | ${reason} | ${winners[reason] ?? 0} |`).join("\n")}\n| grant | authorized (effect act) | ${winners.act ?? 0} |\n\nThe first failing rank wins; invalid effects and expiry prevent semantic evaluation.\nUnevaluable semantic inputs outrank event-type and semantic revocation.\nEvery consumed condition/event pair binds state, canonical clock, RNG, params and optional policy; a callback exception stops evaluation and fails closed.\n`;
}
export async function buildCorpus(seed = SEED) {
  if (seed !== SEED)
    throw new Error(`recorded seed is ${SEED}; unknown seed refused`);
  const kernel = await import(
    pathToFileURL(resolve(ROOT, "packages/kernel/dist/src/index.js"))
  );
  const audit = await import(
    pathToFileURL(resolve(ROOT, "packages/skeleton/dist/src/audit.js"))
  );
  const authority = sweepAuthority(kernel, seed);
  process.stdout.write(
    `authority: ${authority.count} cells, ${authority.calls} predicate calls\n`,
  );
  const outbox = sweepOutbox(kernel, seed);
  process.stdout.write(
    `outbox: ${outbox.count} orders, ${outbox.count * 2} delivery runs\n`,
  );
  const carryIns = auditCarryIns(kernel, audit, seed);
  const files = [];
  const shard = (lane, rows) => {
    for (let i = 0; i < rows.length; i += BUDGET.rowsPerShard) {
      const selected = rows.slice(i, i + BUDGET.rowsPerShard);
      files.push({
        path: `corpus/fixtures/${lane}/wo103-${String(i / BUDGET.rowsPerShard).padStart(3, "0")}.jsonl`,
        rows: selected.length,
        bytes:
          selected
            .map((r, rowIndex) =>
              JSON.stringify(event(`evt_${rowIndex + 1}`, "CorpusFixture", r)),
            )
            .join("\n") + "\n",
      });
    }
  };
  shard("authority", authority.golden);
  shard("outbox", outbox.golden);
  const descriptors = files.map((f) => ({
    path: f.path,
    rows: f.rows,
    bytes: Buffer.byteLength(f.bytes),
    sha256: sha(f.bytes),
  }));
  const fixtureTotals = {
    files: files.length,
    rows: descriptors.reduce((n, f) => n + f.rows, 0),
    bytes: descriptors.reduce((n, f) => n + f.bytes, 0),
  };
  if (
    fixtureTotals.files > BUDGET.maximumFiles ||
    fixtureTotals.rows > BUDGET.maximumRows ||
    fixtureTotals.bytes > BUDGET.maximumTotalBytes
  )
    throw new Error("committed fixture budget exceeded");
  const findings = [
    ...carryIns.map((f) => ({
      number: f.number,
      kind: "unlinked-audit-refusal",
      cellId: f.cellId,
      reproduced: !f.traceLinked,
      input: f.input,
      expected: f.expected,
      events: f.events,
      auditRecords: f.auditRecords,
    })),
    ...(outbox.findingCounts.incompletePending
      ? [
          {
            number: "WO-103-F003",
            kind: "incomplete-command-pending",
            cells: outbox.findingCounts.incompletePending,
            reproduction: outbox.findings.find(
              (f) => f.kind === "incompletePending",
            ),
          },
        ]
      : []),
  ];
  if (authority.findingExamples.length)
    findings.push({
      number: "WO-103-F004",
      kind: "authority-divergence",
      cells: authority.findingCounts.divergence,
      reproductions: authority.findingExamples,
    });
  if (outbox.findingCounts.divergence)
    findings.push({
      number: "WO-103-F005",
      kind: "outbox-divergence",
      cells: outbox.findingCounts.divergence,
      reproductions: outbox.findings.filter(
        (f) => f.kind !== "incompletePending",
      ),
    });
  const table = buildPrecedenceTable(authority.winners);
  files.push({ path: "corpus/manifests/WO-103-precedence.md", bytes: table });
  const findingsText =
    "# WO-103 quarantined findings\n\nObserved shipped behavior; no runtime repair is made by this evidence-only order.\n\n" +
    findings
      .map(
        (f) =>
          `## ${f.number}\n\n${f.kind === "unlinked-audit-refusal" ? "Missing semantic input refuses with the exact partial trace, but deriveAuditRecords omits the DecisionRecorded event from the denied record's eventIds. Carry-in: WO-017 FINAL-001 adjudication 8." : f.kind === "incomplete-command-pending" ? "Replay admits a command with a non-empty string commandId but incomplete Command structure. It reaches pendingCommands; this is quarantined, not asserted valid." : "Shipped behavior diverges from the independent oracle. Reproducing cells are quarantined below."}\n\n\`\`\`json\n${JSON.stringify(f, null, 2)}\n\`\`\`\n`,
      )
      .join("\n");
  files.push({
    path: "corpus/manifests/findings-WO-103.md",
    bytes: findingsText,
  });
  const manifest = {
    schemaVersion: 1,
    workOrderId: "WO-103",
    seed,
    pinnedBaseCommit: BASE,
    provenance:
      "Original generated inputs from personal-project source; no external data or executable functions serialized into fixtures.",
    authority: {
      factors: FACTORS,
      expectedCells: totalCells(),
      observedCells: authority.count,
      expectedStreamSha256: authority.sha256,
      winners: authority.winners,
      observedPredicateCalls: authority.calls,
      divergences: authority.findingCounts.divergence ?? 0,
      inactiveAxes:
        "Zero conditions/events/types retain inactive labels; every Cartesian label tuple still has exactly one cell.",
      predicateRegistry: {
        id: "wo103.probe",
        version: 1,
        semantics:
          "Match selected condition/event indices; bind state, canonical now, RNG, params and optional policy. Throw at the declared early/late callback ordinal. Unknown references preflight before callbacks.",
      },
    },
    outbox: {
      factors: OUTBOX_FACTORS,
      permutationPolicy: PERMUTATION_POLICY,
      delivery: ["once", "each-event-twice"],
      expectedOrders: outboxCount(seed),
      observedOrders: outbox.count,
      expectedRuns: outboxCount(seed) * 2,
      observedRuns: outbox.count * 2,
      expectedStreamSha256: outbox.sha256,
      classifications: outbox.classifications,
      incompletePendingCells: outbox.findingCounts.incompletePending ?? 0,
      divergences: outbox.findingCounts.divergence ?? 0,
      labeledPermutationSlots: true,
    },
    auxiliary: {
      forgedEffects: [null, true, {}, [], "<omitted>"],
      patternProbes: ["a*", "*", "a*b", "a**"],
      deniedListTail: ["other", "a*"],
      identityModes: ["ep", "empty-episode", "no-episode"],
      threadingLimits: [0, 1, 2, 3],
      resourceKeys: ["units", "__proto__", "constructor", "toString"],
      auditCarryInCells: 2,
      standaloneMalformedEnvelope:
        "Not part of the declared set: arbitrary null/malformed envelopes require a separate follow-up.",
    },
    committedBudget: BUDGET,
    fixtures: descriptors,
    fixtureTotals,
    fixtureTransport: {
      protocol: "EventEnvelope v1 JSONL",
      type: "CorpusFixture",
      cellLocation: "payload",
      eventIdPolicy:
        "evt_<physical row>, restarting at evt_1 in each shard; payload.cellId preserves the factorial identity",
      semantics:
        "Synthetic fixture framing only; no runtime event or contract subtype is introduced. Existing strict event codec can decode and re-encode every row.",
    },
    goldenPolicy:
      "512 seeded/level-planted authority cells; one order per outbox factor/alphabet. Full sweeps run and hash every expectation, not just golden cells.",
    generatedSurfaces: [
      { path: "corpus/manifests/WO-103-precedence.md", sha256: sha(table) },
      {
        path: "corpus/manifests/findings-WO-103.md",
        sha256: sha(findingsText),
      },
    ],
    findingNumbers: findings.map((f) => f.number),
    toolchainProfile: TOOLCHAIN,
    evidence: {
      commands: [
        "npm run build",
        `node corpus/harness/generate-authority-corpus.mjs --seed ${SEED} --check`,
        "node --test 'corpus/harness/wo103-*.test.mjs'",
        "npm test",
        "npm run test:docs",
      ],
      runLog: `corpus/manifests/runs/WO-103-${BASE}.log`,
      runLogCommitMeaning:
        "Filename names the pinned base; evidence precedes a final reviewed branch commit.",
      metadataPolicy:
        "Toolchain profile records generation host; regeneration does not require impersonating that host.",
    },
  };
  files.push({ path: MANIFEST_PATH, bytes: json(manifest) });
  return { files, manifest, findings, authority, outbox };
}
export function checkBytes(file, expectedBytes) {
  if (readFileSync(file, "utf8") !== expectedBytes)
    throw new Error(`regeneration drift: ${file}`);
}
export async function runGenerator(argv) {
  if (
    argv.length !== 3 ||
    argv[0] !== "--seed" ||
    !["--write", "--check"].includes(argv[2])
  )
    throw new Error(
      "usage: generate-authority-corpus.mjs --seed <recorded> --write|--check",
    );
  const result = await buildCorpus(argv[1]);
  const mode = argv[2];
  for (const file of result.files) {
    const dest = resolve(ROOT, file.path);
    if (mode === "--write") {
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, file.bytes);
    } else checkBytes(dest, file.bytes);
  }
  // Refuse stale or unmanifested owned shards; never delete them silently.
  for (const lane of ["authority", "outbox"])
    for (const name of readdirSync(resolve(ROOT, `corpus/fixtures/${lane}`))) {
      if (
        name.startsWith("wo103-") &&
        !result.files.some((f) => f.path === `corpus/fixtures/${lane}/${name}`)
      )
        throw new Error(`unmanifested WO-103 shard: ${lane}/${name}`);
    }
  process.stdout.write(
    JSON.stringify({
      mode,
      seed: argv[1],
      authorityCells: result.authority.count,
      outboxRuns: result.outbox.count * 2,
      fixtures: result.manifest.fixtureTotals,
      findings: result.manifest.findingNumbers,
    }) + "\n",
  );
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  runGenerator(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`${error.stack ?? error}\n`);
    process.exitCode = 1;
  });
}
